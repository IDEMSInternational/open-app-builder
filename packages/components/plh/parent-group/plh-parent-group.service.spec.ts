import { TestBed } from "@angular/core/testing";
import { of } from "rxjs";

import { PlhParentGroupService } from "./plh-parent-group.service";

import { AuthService } from "src/app/shared/services/auth/auth.service";
import { DynamicDataService } from "src/app/shared/services/dynamic-data/dynamic-data.service";
import { SharedDataService } from "src/app/feature/shared-data/shared-data.service";
import { RemoteFunctionService } from "src/app/feature/remote-function/remote-function.service";

const PARENT_GROUPS_DATA_LIST = "mock_parent_groups";
const PARENTS_DATA_LIST = "mock_parents";
const MOCK_PARENT_GROUP = { id: "mock_group_id", name: "mock_group", shared_id: "mock_shared_id" };

/**
 * Call standalone tests via:
 * yarn ng test --include ../packages/components/plh/parent-group/plh-parent-group.service.spec.ts
 */
describe("PlhParentGroupService", () => {
  let service: PlhParentGroupService;

  let mockDynamicDataService: jasmine.SpyObj<DynamicDataService>;
  let mockAuthService: jasmine.SpyObj<AuthService>;
  let mockSharedDataService: jasmine.SpyObj<SharedDataService>;
  let mockRemoteFunctionService: jasmine.SpyObj<RemoteFunctionService>;

  beforeEach(() => {
    mockDynamicDataService = jasmine.createSpyObj("DynamicDataService", [
      "query$",
      "ready",
      "remove",
      "upsert",
      "update",
    ]);

    mockAuthService = jasmine.createSpyObj("AuthService", ["ready"]);

    mockSharedDataService = jasmine.createSpyObj("SharedDataService", [
      "ready",
      "setCustomSharedMeta",
    ]);

    mockRemoteFunctionService = jasmine.createSpyObj("RemoteFunctionService", ["ready", "invoke"]);

    TestBed.configureTestingModule({
      providers: [
        { provide: AuthService, useValue: mockAuthService },
        { provide: DynamicDataService, useValue: mockDynamicDataService },
        { provide: SharedDataService, useValue: mockSharedDataService },
        { provide: RemoteFunctionService, useValue: mockRemoteFunctionService },
      ],
    });
    service = TestBed.inject(PlhParentGroupService);
  });

  it("should be created", () => {
    expect(service).toBeTruthy();
  });

  describe("generateAccessCode", () => {
    beforeEach(() => {
      // Return mock parent group (already shared) for parent group queries, no parents for parent queries
      mockDynamicDataService.query$.and.callFake(((_type: string, flow_name: string) =>
        of(flow_name === PARENT_GROUPS_DATA_LIST ? [MOCK_PARENT_GROUP] : [])) as any);
    });

    it("saves access code generated by remote function to local parent group", async () => {
      mockRemoteFunctionService.invoke.and.resolveTo({
        data: { data: { access_code: "AB12" } },
        error: undefined,
      } as any);

      await service.generateAccessCode(
        PARENT_GROUPS_DATA_LIST,
        PARENTS_DATA_LIST,
        MOCK_PARENT_GROUP.id
      );

      expect(mockRemoteFunctionService.invoke).toHaveBeenCalledOnceWith("generateAccessCode", {
        shared_id: MOCK_PARENT_GROUP.shared_id,
      });
      expect(mockDynamicDataService.update).toHaveBeenCalledOnceWith(
        "data_list",
        PARENT_GROUPS_DATA_LIST,
        MOCK_PARENT_GROUP.id,
        { rp_access_code: "AB12" }
      );
      // Remote function saves code to shared data, so should not be written by client
      expect(mockSharedDataService.setCustomSharedMeta).not.toHaveBeenCalled();
    });

    it("does not update local parent group if remote function fails", async () => {
      mockRemoteFunctionService.invoke.and.resolveTo({
        data: undefined,
        error: { code: "resource-exhausted", message: "ACCESS_CODE_GENERATION_FAILED" },
      } as any);
      spyOn(console, "error");

      await service.generateAccessCode(
        PARENT_GROUPS_DATA_LIST,
        PARENTS_DATA_LIST,
        MOCK_PARENT_GROUP.id
      );

      expect(mockRemoteFunctionService.invoke).toHaveBeenCalledTimes(1);
      expect(mockDynamicDataService.update).not.toHaveBeenCalled();
      expect(console.error).toHaveBeenCalled();
    });
  });
});
